#!/usr/bin/env bash
# Deploys ENTX to NEAR testnet:
#   1. creates a faucet-funded contract account and a separate oracle account
#   2. builds + deploys the contract, registers all markets, allow-lists the oracle
#   3. gives the oracle a FUNCTION-CALL-ONLY key limited to `report_epi` on the contract
#   4. writes .env.local so the app's oracle service signs with that restricted key
#
# The server never holds a full-access key: a leaked oracle key can only file EPI reports.
# Requirements: rust + wasm32-unknown-unknown, cargo-near, near-cli-rs, node >= 22 (see README).
set -euo pipefail
cd "$(dirname "$0")/.."

SUFFIX="$(date +%s)"
CONTRACT="${1:-entx-market-$SUFFIX.testnet}"
ORACLE="${2:-entx-oracle-$SUFFIX.testnet}"
NET=(network-config testnet)

for ACC in "$CONTRACT" "$ORACLE"; do
  echo "→ Creating testnet account $ACC (faucet-sponsored)"
  near account create-account sponsor-by-faucet-service "$ACC" autogenerate-new-keypair \
    save-to-legacy-keychain "${NET[@]}" create
done

echo "→ Building contract"
(cd contracts/near && cargo near build non-reproducible-wasm)

echo "→ Deploying + init"
near contract deploy "$CONTRACT" use-file contracts/near/target/near/entx_near.wasm \
  with-init-call new json-args "{\"owner_id\":\"$CONTRACT\"}" \
  prepaid-gas '100.0 Tgas' attached-deposit '0 NEAR' "${NET[@]}" sign-with-legacy-keychain send

echo "→ Registering markets"
TMP="$(mktemp)"
node scripts/markets-json.ts > "$TMP"
near contract call-function as-transaction "$CONTRACT" register_markets file-args "$TMP" \
  prepaid-gas '300.0 Tgas' attached-deposit '0 NEAR' sign-as "$CONTRACT" "${NET[@]}" sign-with-legacy-keychain send
rm -f "$TMP"

echo "→ Allow-listing oracle $ORACLE"
near contract call-function as-transaction "$CONTRACT" add_oracle json-args "{\"account_id\":\"$ORACLE\"}" \
  prepaid-gas '30.0 Tgas' attached-deposit '0 NEAR' sign-as "$CONTRACT" "${NET[@]}" sign-with-legacy-keychain send

echo "→ Adding function-call-only key (report_epi) to $ORACLE"
KEYPAIR="$(node --input-type=module -e "import { KeyPair } from 'near-api-js'; const k = KeyPair.fromRandom('ed25519'); console.log(k.getPublicKey().toString() + ' ' + k.toString());")"
PUB="${KEYPAIR%% *}"
SECRET="${KEYPAIR##* }"
near account add-key "$ORACLE" grant-function-call-access --allowance '1 NEAR' \
  --contract-account-id "$CONTRACT" --function-names 'report_epi' \
  use-manually-provided-public-key "$PUB" "${NET[@]}" sign-with-legacy-keychain send

umask 077
cat > .env.local <<ENV
# Generated by scripts/near-deploy.sh — server-only secrets, never commit.
NEXT_PUBLIC_NEAR_CONTRACT=$CONTRACT
NEAR_ORACLE_ACCOUNT=$ORACLE
# Function-call access key: can only call report_epi on $CONTRACT (1 NEAR gas allowance)
NEAR_ORACLE_PRIVATE_KEY=$SECRET
# Demo mode: in-app oracle buttons may publish (globally rate-limited). Set to false in production.
ENTX_PUBLIC_ORACLE=true
# Bearer secret for server-side publishers (cron/jobs)
ORACLE_API_SECRET=$(node -e "console.log(require('crypto').randomBytes(24).toString('hex'))")
ENV
echo "✓ Deployed. Contract: $CONTRACT · Oracle: $ORACLE — .env.local written. Run: pnpm dev"
