#!/usr/bin/env bash
# Deploys the ENTX contract to a fresh, faucet-funded NEAR testnet account, registers all markets
# and writes .env.local so the app (and its trusted oracle) uses the new contract.
#
# Requirements: rust + wasm32-unknown-unknown target, cargo-near, near-cli-rs (see README).
set -euo pipefail
cd "$(dirname "$0")/.."

ACC="${1:-entx-$(date +%s).testnet}"
echo "→ Creating testnet account $ACC (faucet-sponsored)"
near account create-account sponsor-by-faucet-service "$ACC" autogenerate-new-keypair \
  save-to-legacy-keychain network-config testnet create

echo "→ Building contract"
(cd contracts/near && cargo near build non-reproducible-wasm)

echo "→ Deploying + init"
near contract deploy "$ACC" use-file contracts/near/target/near/entx_near.wasm \
  with-init-call new json-args "{\"owner_id\":\"$ACC\"}" \
  prepaid-gas '100.0 Tgas' attached-deposit '0 NEAR' \
  network-config testnet sign-with-legacy-keychain send

echo "→ Registering markets"
TMP="$(mktemp)"
node scripts/markets-json.ts > "$TMP"
near contract call-function as-transaction "$ACC" register_markets file-args "$TMP" \
  prepaid-gas '300.0 Tgas' attached-deposit '0 NEAR' sign-as "$ACC" \
  network-config testnet sign-with-legacy-keychain send

KEY="$(node -e "console.log(require(process.env.HOME + '/.near-credentials/testnet/$ACC.json').private_key)")"
cat > .env.local <<ENV
# Generated by scripts/near-deploy.sh — server-only secrets, never commit.
NEXT_PUBLIC_NEAR_CONTRACT=$ACC
NEAR_ORACLE_ACCOUNT=$ACC
NEAR_ORACLE_PRIVATE_KEY=$KEY
ENV
chmod 600 .env.local
echo "✓ Deployed. Contract: $ACC — .env.local written. Run: pnpm dev"
